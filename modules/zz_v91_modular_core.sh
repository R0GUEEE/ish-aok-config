workspace_report_v91(){
  command_registry_build
  printf 'iSH-AOK Workspace — Unified Workspace\n'
  printf 'Modular Core: v9.1 declarative navigation\n\n%s\n' "$(v90_workspace_summary)"
  printf 'Registered actions: %s\n' "$(awk 'END{print NR+0}' "$V73_ACTIONS_FILE")"
  printf 'Declarative menus: %s\n' "$(find "$V91_MENU_DIR" -name '*.menu' -type f 2>/dev/null | wc -l | tr -d ' ')"
  awk -F '\t' '{printf "%-20s %-14s %s\n",$1,$3,$2}' "$V73_ACTIONS_FILE"
}

